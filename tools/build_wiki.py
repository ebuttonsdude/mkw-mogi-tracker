#!/usr/bin/env python3
"""Export the documentation to plain GitHub wiki Markdown, without publishing it."""

import argparse
from pathlib import Path, PurePosixPath
import posixpath
import re
import shutil
import sys
from urllib.parse import quote, unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from tools.build_docs import SCREENSHOTS  # noqa: E402

REPOSITORY = 'https://github.com/ebuttonsdude/mkw-mogi-tracker'
SITE = 'https://ebuttonsdude.github.io/mkw-mogi-tracker/'
RAW = 'https://raw.githubusercontent.com/ebuttonsdude/mkw-mogi-tracker/main/'
OUTPUT_MARKER = '.mkw-wiki-output'
MARKER_CONTENT = 'Generated by tools/build_wiki.py; not tracker data.\n'
LINK = re.compile(r'(!?\[[^\]]*\]\()([^\s)]+)([^\n)]*\))')
INLINE_CODE = re.compile(r'(`+)(.+?)\1')
FENCE = re.compile(r'^ {0,3}(`{3,}|~{3,})')
SHORTCODE = re.compile(r'\{\{<\s*(.*?)\s*>\}\}')
SOURCE_FILES = {'README.md', 'DESIGN.md', 'AGENTS.md', 'ATTRIBUTION.md', 'LICENSE',
                'COPYING.md', 'THIRD_PARTY_NOTICES.md', 'pyproject.toml', '.gitignore'}
SOURCE_DIRS = {'docs', 'tools', 'tests', 'mkw_tracker', 'LICENSES'}


def page_slug(relative):
    """Flatten paths, refusing ambiguous names when the inventory is assembled."""
    if relative == PurePosixPath('_index.md'):
        return 'Home'
    parts = list(relative.with_suffix('').parts)
    if parts[-1] == '_index':
        parts.pop()
    slug = '-'.join(parts)
    if not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', slug):
        raise ValueError(f'Unsupported wiki source name: {relative}')
    return slug


def read_page(source):
    text = source.read_text(encoding='utf-8')
    if not text.startswith('---\n') or '\n---\n' not in text[4:]:
        raise ValueError(f'Missing documentation front matter: {source}')
    front, body = text[4:].split('\n---\n', 1)
    title = re.search(r'^title:\s*(.+?)\s*$', front, re.MULTILINE)
    if not title:
        raise ValueError(f'Missing documentation title: {source}')
    title = title[1].strip().strip('"\'')
    weight = re.search(r'^weight:\s*(\d+)\s*$', front, re.MULTILINE)
    return title, int(weight[1]) if weight else 1000, body.lstrip('\n')


def public_path(root, source, link):
    parsed = urlsplit(link)
    decoded = unquote(parsed.path)
    if '\\' in decoded or decoded.startswith('/'):
        raise ValueError(f'Unsupported local documentation link: {link}')
    relative = PurePosixPath(posixpath.normpath(str(source.parent / decoded)))
    if '..' in relative.parts or not relative.parts:
        raise ValueError(f'Documentation link escapes the repository: {link}')
    if str(relative) not in SOURCE_FILES and relative.parts[0] not in SOURCE_DIRS:
        raise ValueError(f'Documentation link is not a public source path: {link}')
    target = root.joinpath(*relative.parts)
    if any(root.joinpath(*relative.parts[:i]).is_symlink() for i in range(1, len(relative.parts) + 1)):
        raise ValueError(f'Documentation symlink is not published: {link}')
    if not target.exists():
        raise ValueError(f'Missing documentation link target: {link}')
    return relative, target, parsed


def rewrite_link(root, source, link, pages, image=False):
    parsed = urlsplit(link)
    if parsed.scheme or parsed.netloc or not parsed.path:
        return link
    relative, target, parsed = public_path(root, source, link)
    suffix = ('?' + parsed.query if parsed.query else '') + ('#' + parsed.fragment if parsed.fragment else '')
    if image:
        if relative.parent != PurePosixPath('docs/images') or relative.name not in SCREENSHOTS:
            raise ValueError(f'Image is not an approved documentation screenshot: {link}')
        return RAW + quote(str(relative), safe='/') + suffix
    if relative in pages:
        return REPOSITORY + '/wiki/' + pages[relative]['slug'] + suffix
    kind = 'tree' if target.is_dir() else 'blob'
    return f'{REPOSITORY}/{kind}/main/{quote(str(relative), safe="/")}' + suffix


def convert_body(root, source, body, pages):
    """Translate the current docs syntax, preserving fenced and inline examples."""
    shortcodes = []

    def shortcode(match):
        token = match[1]
        if token.startswith('/'):
            name = token[1:]
            if not shortcodes or shortcodes.pop() != name:
                raise ValueError(f'Unbalanced documentation shortcode in {source}: {token}')
            return ''
        if token == 'distro-picker':
            shortcodes.append(token)
            return '**Choose the prerequisites for your distribution below, then continue with the shared setup steps.**'
        distro = re.fullmatch(r'(distro|distro-note) "(arch|fedora|ubuntu)"', token)
        if distro:
            shortcodes.append(distro[1])
            if distro[1] == 'distro-note':
                label = {'arch': 'Arch Linux', 'fedora': 'Fedora', 'ubuntu': 'Ubuntu'}[distro[2]]
                return f'**{label} note:**'
            return ''
        raise ValueError(f'Unsupported documentation shortcode in {source}: {token}')

    def prose(text):
        text = SHORTCODE.sub(shortcode, text)
        if '{{<' in text or '{{%' in text:
            raise ValueError(f'Unsupported shortcode syntax in {source}')
        if re.search(r'<(?:a|img)\b[^>]*(?:href|src)\s*=', text, re.IGNORECASE):
            raise ValueError(f'Use Markdown links/images in wiki documentation: {source}')
        if re.search(r'^ {0,3}\[[^]]+\]:', text, re.MULTILINE):
            raise ValueError(f'Use inline Markdown links in wiki documentation: {source}')
        return text

    def convert_chunk(text):
        pieces = []
        start = 0
        while start < len(text):
            link = LINK.search(text, start)
            code = INLINE_CODE.search(text, start)
            matches = [match for match in (link, code) if match is not None]
            if not matches:
                pieces.append(prose(text[start:]))
                break
            match = min(matches, key=lambda item: item.start())
            pieces.append(prose(text[start:match.start()]))
            if match is link:
                pieces.append(match[1] + rewrite_link(root, source, match[2], pages,
                                                     match[1].startswith('!')) + match[3])
            else:
                pieces.append(match[0])
            start = match.end()
        return ''.join(pieces)

    output = []
    pending = []
    fence = None
    for line in body.splitlines(keepends=True):
        found = FENCE.match(line)
        if fence:
            output.append(line)
            if found and found[1][0] == fence[0] and len(found[1]) >= len(fence) and not line[found.end():].strip():
                fence = None
        elif found:
            output.append(convert_chunk(''.join(pending)))
            pending.clear()
            fence = found[1]
            output.append(line)
        else:
            pending.append(line)
    output.append(convert_chunk(''.join(pending)))
    if fence or shortcodes:
        raise ValueError(f'Unclosed code fence or shortcode in {source}')
    return ''.join(output)


def render_wiki(root):
    docs = root / 'docs'
    if docs.is_symlink() or any(path.is_symlink() for path in docs.rglob('*')):
        raise ValueError('Documentation symlinks are not published.')
    pages = {}
    slugs = set()
    for source in sorted(docs.rglob('*.md')):
        relative = source.relative_to(docs)
        if relative.parts[0] == 'images':
            continue  # Screenshot provenance stays in the source repository.
        slug = page_slug(PurePosixPath(relative.as_posix()))
        if slug.lower() in slugs:
            raise ValueError(f'Duplicate wiki page name: {slug}')
        slugs.add(slug.lower())
        title, weight, body = read_page(source)
        pages[PurePosixPath('docs') / relative.as_posix()] = {
            'slug': slug, 'title': title, 'weight': weight, 'body': body,
        }
    if PurePosixPath('docs/_index.md') not in pages:
        raise ValueError('docs/_index.md is required as the wiki home page.')
    output = {}
    for source, page in pages.items():
        notice = (f'> Automatically generated from [the documentation source]({REPOSITORY}/blob/main/{source}). '
                  f'Use the [documentation website]({SITE}) for the full presentation. '
                  'Edit the source rather than these generated pages; direct wiki edits block the next sync.\n\n')
        output[page['slug'] + '.md'] = notice + convert_body(root, source, page['body'], pages).rstrip() + '\n'
    navigation = [f'**[Documentation website]({SITE})**\n', '\n']
    ordered = sorted(pages.values(), key=lambda page: (page['slug'] != 'Home', page['weight'], page['slug']))
    for page in ordered:
        title = page['title'].replace('[', '\\[').replace(']', '\\]')
        navigation.append(f'- [{title}]({REPOSITORY}/wiki/{page["slug"]})\n')
    output['_Sidebar.md'] = ''.join(navigation)
    return output


def publish_output(output, destination):
    if any(path.is_symlink() for path in (destination, *destination.parents)):
        raise ValueError('The wiki destination must not be a symlink.')
    if any(not re.fullmatch(r'(?:Home|_Sidebar|[a-z0-9]+(?:-[a-z0-9]+)*)\.md', name) for name in output):
        raise ValueError('Unsafe generated wiki filename.')
    if destination.exists():
        if not destination.is_dir():
            raise ValueError('The wiki destination must be a directory.')
        if any(destination.iterdir()):
            marker = destination / OUTPUT_MARKER
            if marker.is_symlink() or not marker.is_file() or marker.read_text() != MARKER_CONTENT:
                raise ValueError(f'Refusing to replace an unowned nonempty directory: {destination}')
            shutil.rmtree(destination)
    destination.mkdir(parents=True, exist_ok=True)
    for name, body in output.items():
        (destination / name).write_text(body, encoding='utf-8')
    (destination / OUTPUT_MARKER).write_text(MARKER_CONTENT, encoding='utf-8')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--destination', type=Path, default=ROOT / '.local' / 'wiki-public')
    args = parser.parse_args(argv)
    try:
        output = render_wiki(ROOT)
        publish_output(output, args.destination.absolute())
    except (OSError, ValueError) as error:
        print(f'Wiki build failed: {error}', file=sys.stderr)
        return 1
    print(f'Exported {len(output) - 1} documentation pages and a sidebar: {args.destination}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
